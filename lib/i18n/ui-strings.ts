export const UI_STRINGS: Record<UiLang, UiDict> = {
  en: UI_EN,
  ar,
  ur,
  ro,
  pl,
  pt,
  bn,
  fa,
};

export function toUiLang(lang: TranslationLang): UiLang {
  if (lang === 'off') return 'en';
  return lang;
}

export function t(
  lang: TranslationLang,
  key: UiKey,
  vars?: Record<string, string | number>
): string {
  const ui = toUiLang(lang);
  let s = UI_STRINGS[ui][key] || UI_STRINGS.en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

/** Secondary support line under English UI. Returns null when English is selected. */
export function getUiTranslation(
  lang: TranslationLang,
  key: UiKey,
  vars?: Record<string, string | number>
): string | null {
  if (lang === 'off') return null;
  return t(lang, key, vars);
}

/** Canonical English label for bilingual UI (primary line always English). */
export function enLabel(key: UiKey, vars?: Record<string, string | number>): string {
  return t('off', key, vars);
}
